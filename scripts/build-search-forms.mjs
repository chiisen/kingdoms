/* Generates src/game/search-forms.ts: the Simplified rendition of every officer's
   searchable text (name, role and speciality). The roster search matches a query
   against the Traditional text and against this record, so both scripts find the
   same officers without shipping a conversion library to the browser.

   Usage: node scripts/build-search-forms.mjs */

import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';
import * as OpenCC from 'opencc-js';

const OUTPUT = 'src/game/search-forms.ts';

async function loadOfficers() {
  const bundle = await build({
    entryPoints: ['src/game/officers.ts'],
    bundle: true,
    format: 'esm',
    platform: 'node',
    write: false,
  });
  return import(
    'data:text/javascript;base64,' +
      Buffer.from(bundle.outputFiles[0].text).toString('base64')
  );
}

/** The file content, so the sync test can compare it with what is committed. */
export async function buildSearchForms() {
  const { ALL_OFFICERS } = await loadOfficers();
  const toSimplified = OpenCC.Converter({ from: 'tw', to: 'cn' });

  const entries = [];
  for (const officer of ALL_OFFICERS) {
    const traditional = `${officer.name}${officer.role}${officer.specialty}`;
    const simplified = toSimplified(traditional);
    // Only officers whose text actually differs need a second record.
    if (simplified !== traditional) entries.push([officer.id, simplified]);
  }

  const body = entries
    .map(([id, text]) => `  ${id}: '${text}',`)
    .join('\n');
  return `/* Generated by scripts/build-search-forms.mjs — do not edit by hand.
   Simplified spellings of the officers whose name, role or speciality differ from
   the Traditional interface text, so the roster search accepts either script. */

export const SIMPLIFIED_FORMS: Record<string, string> = {
${body}
};
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const content = await buildSearchForms();
  writeFileSync(OUTPUT, content);
  const count = content.split('\n').filter((line) => line.startsWith('  ')).length;
  console.log(`wrote ${OUTPUT} (${count} Simplified spellings)`);
}
